"""Generate transparent exports for OpenXR 1.0 plus Android loader initialization."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent
header = (root / 'include/openxr/openxr.h').read_text()
core = header.split('// XR_VERSION_1_1')[0]
custom = {'xrGetInstanceProcAddr', 'xrCreateInstance', 'xrDestroyInstance',
          'xrCreateSession', 'xrDestroySession', 'xrBeginSession',
          'xrCreateSwapchain', 'xrDestroySwapchain', 'xrWaitFrame',
          'xrApplyHapticFeedback', 'xrStopHapticFeedback', 'xrEndSession',
          'xrCreateAction', 'xrDestroyAction', 'xrDestroyActionSet'}
diagnostics = {'xrCreateAction', 'xrGetCurrentInteractionProfile', 'xrGetActionStateBoolean', 'xrSuggestInteractionProfileBindings', 'xrSyncActions'}
prototypes = re.findall(r'XRAPI_ATTR XrResult XRAPI_CALL (xr\w+)\(\s*(.*?)\);', header, re.S)
out = ['// Generated by generate_forwarders.py; do not edit.']
for name, args in prototypes:
    if name in custom or (name not in core and name != 'xrInitializeLoaderKHR'):
        continue
    params = [re.search(r'(\w+)\s*(?:\[[^]]*\])?$', arg.strip()).group(1) for arg in args.split(',')]
    body = f'''extern "C" XRAPI_ATTR XrResult XRAPI_CALL {name}({args}) {{
    auto fn = symbol<PFN_{name}>("{name}");
    return fn ? fn({', '.join(params)}) : XR_ERROR_FUNCTION_UNSUPPORTED;
}}'''
    out.append(f'#ifndef GXR_INPUT_DIAGNOSTICS\n{body}\n#endif' if name in diagnostics else body)
(root / 'forwarders.inc').write_text('\n\n'.join(out) + '\n')
